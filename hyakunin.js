/** 編集距離(レーベンシュタイン距離) */
export function editDistance(a, b) {
  const A = [...a], B = [...b];
  let prev = Array.from({ length: B.length + 1 }, (_, j) => j);
  for (let i = 1; i <= A.length; i++) {
    const cur = [i];
    for (let j = 1; j <= B.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (A[i - 1] === B[j - 1] ? 0 : 1));
    }
    prev = cur;
  }
  return prev[B.length];
}

/** 読み取った文字から、空白・句読点・記号を除く */
function normalize(s) {
  return [...(s || '').replace(/[\s　、。・,.「」『』()（）︵︶…]/g, '')];
}

/**
 * text の先頭が句 ku に合うか。読み取りの誤りで字が増えたり減ったりしてもよいように、長さ ±1 の先頭も比べる。
 * @returns {{dist: number, len: number}} 編集距離と、合った先頭の長さ
 */
function matchHead(chars, ku) {
  const n = [...ku].length;
  let best = { dist: Infinity, len: 0 };
  for (let len = Math.max(1, n - 1); len <= Math.min(chars.length, n + 1); len++) {
    const d = editDistance(chars.slice(0, len).join(''), ku);
    if (d < best.dist || (d === best.dist && Math.abs(len - n) < Math.abs(best.len - n))) best = { dist: d, len };
  }
  return best;
}

/** rest(初句の後ろの字)が、第 2 句の書き始めとどれだけ合うか(合った字数) */
function hintLength(rest, poem) {
  let best = 0;
  for (const ku of [poem.ku[1], poem.kanaKu[1]]) {
    const k = [...ku];
    let n = 0;
    while (n < rest.length && n < k.length && rest[n] === k[n]) n++;
    best = Math.max(best, n);
  }
  return best;
}

/**
 * プリントの文字(初句と、続きの手がかりの字)から、歌の候補を出す。
 * 初句の表記かかなが、ほぼ合う歌だけを返す(4 字につき 1 字の読み違いまで)。
 * 初句が同じ歌(わたの原・君がため・朝ぼらけ)は、手がかりの字(例: わたの原 や → 八十島かけて)で並べる。
 * @returns {{poem: object, prompt: string, dist: number}[]} よく合う順。prompt は出題で見せる文字(例:「わたの原 や」)
 */
export function matchPoems(text) {
  const chars = normalize(text);
  if (chars.length < 2) return [];
  const out = [];
  for (const poem of POEMS) {
    let m = null;
    for (const ku of [poem.ku[0], poem.kanaKu[0]]) {
      const r = matchHead(chars, ku);
      const allow = Math.floor([...ku].length / 4);
      if (r.dist <= allow && (!m || r.dist < m.dist)) m = r;
    }
    if (!m) continue;
    const rest = chars.slice(m.len);
    const hint = hintLength(rest, poem);
    const prompt = poem.ku[0] + (hint ? ' ' + rest.slice(0, hint).join('') : '');
    out.push({ poem, prompt, dist: m.dist, hint });
  }
  return out
    .sort((a, b) => a.dist - b.dist || b.hint - a.hint || a.poem.no - b.poem.no)
    .map(({ poem, prompt, dist }) => ({ poem, prompt, dist }));
}

